@dataclass(slots=True)
class HeronError(Exception):
    """Ошибка, останавливающая сборку."""

    code: str
    message: str
    path: str | None = None
    line: int | None = None
    hint: str | None = None

    def __str__(self) -> str:
        return self.render("ru")

    def render(self, lang: str, /) -> str:
        """Ошибка одной строкой на языке сообщений (подробность и подсказка по lang)."""
        from heron.messages import rendered, say

        where = rendered(self.path, lang) or say(lang, "summary_unknown_file")
        if self.line is not None:
            where = f"{where}:{self.line}"
        text = f"{self.code} {where}: {rendered(self.message, lang)}"
        if self.hint:
            text = f"{text}\n" + say(lang, "error_hint", hint=rendered(self.hint, lang))
        return text


@dataclass(slots=True)
class Warning_:
    """Предупреждение. Не останавливает сборку, попадает в отчёт check.

    `kind` — вид предупреждения. Сводка группирует по нему, иначе сотня
    однотипных замечаний про переводы прячет десяток важных про файлы,
    которых нет на диске.
    """

    message: str
    path: str | None = None
    line: int | None = None
    kind: str = "прочее"


@dataclass(slots=True)
class Collector:
    """Копит ошибки и предупреждения, чтобы показать все сразу, а не по одной за прогон."""

    errors: list[HeronError] = field(default_factory=list)
    warnings: list[Warning_] = field(default_factory=list)

    def error(self, *args, **kwargs) -> None:
        self.errors.append(HeronError(*args, **kwargs))

    def warn(self, *args, **kwargs) -> None:
        self.warnings.append(Warning_(*args, **kwargs))

    @property
    def failed(self) -> bool:
        return bool(self.errors)
