"""scripts/check_commit_messages.sh: атрибуция помощников в сообщениях коммитов.

Правило — docs/ru/spec/23-distribution.md §9 и AGENTS.md: сообщение о правке, не
об инструменте. Скрипт смотрит коммиты origin/prod..HEAD (или prod..HEAD) и
падает с хешем нарушителя. Каждый тест строит свой репозиторий во временной папке.
"""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "check_commit_messages.sh"

pytestmark = pytest.mark.skipif(shutil.which("git") is None, reason="нет git")

# Строки нарушений собраны из частей: этот файл сам по себе — не сообщение
# коммита, но так в исходнике не остаётся готовой строки атрибуции.
TRAILER = "Co-" + "Authored-By: Helper <helper@example.org>"
VENDOR_MAIL = "Co-" + "Authored-By: Claude <noreply@" + "anthropic.com>"
GENERATED = "\N{ROBOT FACE} Generated with [Claude Code](https://example.org/code)"


def _git(repo: Path, *args: str) -> str:
    env = {
        **os.environ,
        "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_AUTHOR_NAME": "Tester",
        "GIT_AUTHOR_EMAIL": "tester@example.org",
        "GIT_COMMITTER_NAME": "Tester",
        "GIT_COMMITTER_EMAIL": "tester@example.org",
    }
    done = subprocess.run(
        ["git", "-c", "commit.gpgsign=false", "-c", "init.defaultBranch=prod", *args],
        cwd=repo,
        env=env,
        capture_output=True,
        text=True,
        check=True,
    )
    return done.stdout.strip()


def _commit(repo: Path, message: str) -> str:
    _git(repo, "commit", "-q", "--allow-empty", "-m", message)
    return _git(repo, "rev-parse", "--short", "HEAD")


def _repo(tmp_path: Path) -> Path:
    """Репозиторий: prod с одним коммитом, рабочая ветка feature от него."""
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q")
    _commit(repo, "начало")
    _git(repo, "checkout", "-q", "-b", "feature")
    return repo


def _check(repo: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["bash", str(SCRIPT)], cwd=repo, capture_output=True, text=True, check=False
    )


def test_good_commits_pass(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    _commit(repo, "[E1.S1.T1] Правка шаблона\n\nОбновлены CLAUDE.md и GEMINI.md, AGENTS.md.")
    _commit(repo, "[E1.S1.T2] Сборка: generated with jinja, без изменений в выводе")
    _commit(repo, "[E1.S1.T3] Правка указателя CLAUDE.md: claude.md в нижнем регистре тоже имя")
    _commit(repo, "[E1.S1.T4] Индекс generated with правилами из CLAUDE.md и GEMINI.md")
    # Слова, внутри которых есть имя компании или помощника (E13.S1.T20, W1).
    _commit(repo, "[E1.S1.T5] Страница philanthropic fundraiser и misanthropic-эссе")
    _commit(repo, "[E1.S1.T6] Список generated with cursor-based pagination")
    _commit(repo, "[E1.S1.T7] Fix CLAUDE.MD pointer; Claude wrote this")
    _commit(repo, "[E1.S1.T8] Отчёт generated by GEMINI.md tooling")
    done = _check(repo)
    assert done.returncode == 0, done.stderr
    assert "8 после prod — чисто" in done.stdout


@pytest.mark.parametrize(
    "message",
    [
        f"[E1] Правка\n\n{TRAILER}",
        "[E1] Правка\n\nco-authored-by: someone <a@example.org>",
        f"[E1] Правка\n\n{VENDOR_MAIL}",
        "[E1] Правка по совету Anthropic",
        "[E1] Правка\n\nподсказка от OpenAI",
        f"[E1] Правка\n\n{GENERATED}",
        "[E1] Правка, generated by Copilot",
        # Имя помощника перед точкой, но не «.md» (E13.S1.T20, I1).
        "[E1] Правка\n\nGenerated with GitHub Copilot.",
        "[E1] Правка\n\ngenerated by claude.ai",
        "[E1] Правка\n\nGenerated with Cursor IDE",
        "[E1] Правка\n\nnoreply@" + "anthropic.com",
    ],
)
def test_bad_commit_fails_with_its_hash(tmp_path: Path, message: str) -> None:
    repo = _repo(tmp_path)
    _commit(repo, "[E1] хороший коммит до")
    bad = _commit(repo, message)
    _commit(repo, "[E1] хороший коммит после")
    done = _check(repo)
    assert done.returncode == 1
    assert f"коммит {bad} «[E1] " in done.stderr
    assert "1 из 3 после prod" in done.stderr


def test_every_bad_commit_is_named(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    first = _commit(repo, f"[E1] первый\n\n{TRAILER}")
    _commit(repo, "[E1] хороший")
    second = _commit(repo, f"[E1] второй\n\n{GENERATED}")
    done = _check(repo)
    assert done.returncode == 1
    assert f"коммит {first} «[E1] первый»" in done.stderr
    assert f"коммит {second} «[E1] второй»" in done.stderr
    assert "строка 3: " in done.stderr
    assert "2 из 3 после prod" in done.stderr


def test_commits_already_in_prod_are_not_checked(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    _git(repo, "checkout", "-q", "prod")
    _commit(repo, f"[E0] старое, уже в prod\n\n{TRAILER}")
    _git(repo, "checkout", "-q", "-B", "feature")
    _commit(repo, "[E1] новое")
    done = _check(repo)
    assert done.returncode == 0, done.stderr
    assert "1 после prod — чисто" in done.stdout


def test_origin_prod_wins_over_local_prod(tmp_path: Path) -> None:
    """Локальный prod отстал, origin/prod уже содержит старый плохой коммит."""
    repo = _repo(tmp_path)
    _commit(repo, f"[E0] уже опубликовано\n\n{TRAILER}")
    _git(repo, "update-ref", "refs/remotes/origin/prod", "HEAD")
    _commit(repo, "[E1] новое")
    done = _check(repo)
    assert done.returncode == 0, done.stderr
    assert "1 после origin/prod — чисто" in done.stdout
    # Без origin/prod тот же коммит виден от локального prod.
    _git(repo, "update-ref", "-d", "refs/remotes/origin/prod")
    assert _check(repo).returncode == 1


def test_no_prod_branch_is_skipped(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    _commit(repo, f"[E1] плохое\n\n{TRAILER}")
    _git(repo, "branch", "-q", "-m", "prod", "old")
    done = _check(repo)
    assert done.returncode == 0
    assert "нет ни origin/prod, ни prod — пропуск" in done.stdout


def test_no_git_history_is_skipped(tmp_path: Path) -> None:
    folder = tmp_path / "archive"
    folder.mkdir()
    env = {**os.environ, "GIT_CEILING_DIRECTORIES": str(tmp_path)}
    done = subprocess.run(
        ["bash", str(SCRIPT)], cwd=folder, env=env, capture_output=True, text=True, check=False
    )
    assert done.returncode == 0
    assert "истории git нет — пропуск" in done.stdout


def test_check_sh_runs_both_checks() -> None:
    text = (ROOT / "scripts" / "check.sh").read_text(encoding="utf-8")
    assert "bash scripts/check_commit_messages.sh ||" in text
    assert "py scripts/check_translation.py ||" in text
